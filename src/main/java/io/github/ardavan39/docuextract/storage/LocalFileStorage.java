package io.github.ardavan39.docuextract.storage;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Component;

import io.github.ardavan39.docuextract.config.AppProperties;

@Component
public class LocalFileStorage implements FileStorage {

    private final Path root;

    @Autowired
    public LocalFileStorage(AppProperties properties) {
        this(properties.storage().directory());
    }

    LocalFileStorage(Path root) {
        this.root = root.toAbsolutePath().normalize();
        try {
            Files.createDirectories(this.root);
        } catch (IOException e) {
            throw new StorageException("Cannot create storage directory " + this.root, e);
        }
    }

    @Override
    public void store(String key, byte[] content) {
        try {
            Files.write(resolve(key), content);
        } catch (IOException e) {
            throw new StorageException("Cannot store " + key, e);
        }
    }

    @Override
    public byte[] load(String key) {
        try {
            return Files.readAllBytes(resolve(key));
        } catch (NoSuchFileException e) {
            throw new StorageException("No stored file for " + key, e);
        } catch (IOException e) {
            throw new StorageException("Cannot read " + key, e);
        }
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException e) {
            throw new StorageException("Cannot delete " + key, e);
        }
    }

    /** Keys are generated by the service, but refuse anything that would leave the root anyway. */
    private Path resolve(String key) {
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root) || path.equals(root)) {
            throw new StorageException("Invalid storage key: " + key);
        }
        return path;
    }
}
